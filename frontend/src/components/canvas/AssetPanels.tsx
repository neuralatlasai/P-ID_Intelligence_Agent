/** The symbol as drawn, cropped out of the real sheet. The one image here that is not simulated. */
function SymbolCrop({
  node,
  imageUrl,
  sheet,
}: {
  readonly node: DrawingNode;
  readonly imageUrl: string;
  readonly sheet: { readonly width: number; readonly height: number };
}) {
  const view = 104;
  // Frame a little context around the symbol so its connections are visible too.
  const span = Math.max(node.width, node.height, 24) * 3.2;
  const scale = view / span;
  const style: CSSProperties = {
    backgroundImage: `url("${imageUrl}")`,
    backgroundSize: `${sheet.width * scale}px ${sheet.height * scale}px`,
    backgroundPosition: `${-(node.x - span / 2) * scale}px ${-(node.y - span / 2) * scale}px`,
  };
  return (
    <figure className={styles.crop}>
      <div style={style} role="img" aria-label="Symbol as drawn on the sheet" />
      <figcaption>As drawn</figcaption>
    </figure>
  );
}

export function AssetPopover({
  node,
  asset,
  line,
  printedTag,
  className,
  imageUrl,
  sheet,
  joined,
  register,
  onSelectNode,
  onViewAsset,
  onShowRelated,
  onReadTag,
  onAsk,
  onDismiss,
}: {
  readonly node: DrawingNode;
  readonly asset?: AssetRecord | undefined;
  readonly line?: LineRecord | undefined;
  readonly printedTag?: string | undefined;
  readonly className: string;
  readonly imageUrl: string;
  readonly sheet: { readonly width: number; readonly height: number };
  readonly joined: readonly { readonly id: string; readonly hops: number }[];
  readonly register: PlantRegister;
  readonly onSelectNode: (id: string) => void;
  readonly onViewAsset: () => void;
  readonly onShowRelated: () => void;
  readonly onReadTag: () => void;
  readonly onAsk: () => void;
  readonly onDismiss: () => void;
}) {
  // A pipe-run selection: a connector or crossing is part of a line, and the line is what an
  // engineer means when they click on pipework.
  if (!asset && line) {
    return (
      <div className={styles.popover} aria-hidden="true">
        <header>
          <div>
            <strong>{line.number}</strong>
            <p>
              Pipe run · {line.sizeInches}&quot; {line.service.name}
            </p>
          </div>
          <button type="button" tabIndex={-1} onClick={onDismiss} aria-label="Close">
            ✕
          </button>
        </header>
        <div className={styles.popoverTop}>
          <SymbolCrop node={node} imageUrl={imageUrl} sheet={sheet} />
          <dl className={styles.facts}>
            <div>
              <dt>Nominal size</dt>
              <dd>{line.sizeInches}&quot;</dd>
            </div>
            <div>
              <dt>Service</dt>
              <dd>
                {line.service.code} · {line.service.name}
              </dd>
            </div>
            <div>
              <dt>Piping class</dt>
              <dd>{line.pipeClass}</dd>
            </div>
            <div>
              <dt>Components</dt>
              <dd>{line.assets.length}</dd>
            </div>
          </dl>
        </div>
        {line.assets.length > 0 && (
          <div className={styles.tagCloud}>
            {line.assets.slice(0, 18).map((id) => (
              <button key={id} type="button" tabIndex={-1} onClick={() => onSelectNode(id)}>
                {register.assets.get(id)?.tag ?? id}
              </button>
            ))}
            {line.assets.length > 18 ? <span>+{line.assets.length - 18}</span> : null}
          </div>
        )}
        <footer>
          <SimulatedBadge label="Simulated line number" />
          <button type="button" tabIndex={-1} onClick={onAsk}>
            Ask about this line
          </button>
        </footer>
      </div>
    );
  }

  const tag = printedTag ?? asset?.tag ?? node.id;
  const openOrders = asset?.workOrders.filter((w) => w.status !== "Closed").length ?? 0;
  const lineNumber = asset?.lines[0]
    ? register.lines.get(asset.lines[0])?.number
    : undefined;
  const loopPartner = asset?.loop
    ? [...register.assets.values()].find(
        (a) => a.loop === asset.loop && a.tag !== asset.tag,
      )
    : undefined;

  return (
    <div className={styles.popover} aria-hidden="true">
      <header>
        <div>
          <strong>{tag}</strong>
          <p>{asset?.name ?? className}</p>
        </div>
        <button type="button" tabIndex={-1} onClick={onDismiss} aria-label="Close">
          ✕
        </button>
      </header>
      <div className={styles.popoverTop}>
        <SymbolCrop node={node} imageUrl={imageUrl} sheet={sheet} />
        <div className={styles.popoverSummary}>
          {asset ? <StatusChip value={asset.status} /> : null}
          <dl className={styles.facts}>
            <div>
              <dt>Type</dt>
              <dd>{asset?.name ?? className}</dd>
            </div>
            <div>
              <dt>Area</dt>
              <dd>
                {register.area} · {register.service.code}
              </dd>
            </div>
            {lineNumber ? (
              <div>
                <dt>Line</dt>
                <dd>{lineNumber}</dd>
              </div>
            ) : null}
            {asset?.loop ? (
              <div>
                <dt>Loop</dt>
                <dd>
                  {asset.loop}
                  {loopPartner ? ` · ${loopPartner.tag}` : ""}
                </dd>
              </div>
            ) : null}
            <div>
              <dt>Connected</dt>
              <dd>
                {joined.length} {joined.length === 1 ? "component" : "components"}
              </dd>
            </div>
            <div>
              <dt>Open WOs</dt>
              <dd className={openOrders ? styles.alert : undefined}>{openOrders}</dd>
            </div>
          </dl>
        </div>
      </div>
      {printedTag ? (
        <p className={styles.provenance}>Tag read from the drawing</p>
      ) : (
        <p className={styles.provenance}>
          <SimulatedBadge label="Simulated tag" /> Source node {node.id}
        </p>
      )}
      <footer>
        <button type="button" tabIndex={-1} onClick={onViewAsset}>
          View asset
        </button>
        <button type="button" tabIndex={-1} onClick={onShowRelated}>
          Show related
        </button>
        {!printedTag ? (
          <button type="button" tabIndex={-1} onClick={onReadTag}>
            Read printed tag
          </button>
        ) : null}
        <button
          type="button"
          tabIndex={-1}
          className={styles.primaryAction}
          onClick={onAsk}
        >
          Ask agent
        </button>
      </footer>
    </div>
  );
}

