/** Marks a panel whose contents come from the simulated register. */
export function SimulatedBadge({ label = "Simulated" }: { readonly label?: string }) {
  return (
    <span
      className={styles.simulated}
      title="Generated by the workspace register for demonstration. Not plant data."
    >
      {label}
    </span>
  );
}

const STATUS_CLASS: Record<string, string | undefined> = {
  "In service": styles.statusOk,
  Standby: styles.statusWarn,
  "Under maintenance": styles.statusBad,
  Open: styles.statusBad,
  "In progress": styles.statusWarn,
  Planned: styles.statusInfo,
  Closed: styles.statusOk,
  High: styles.statusBad,
  Medium: styles.statusWarn,
  Low: styles.statusOk,
};

/** A status word in a coloured chip. The word always carries the meaning; colour repeats it. */
export function StatusChip({ value }: { readonly value: string }) {
  return (
    <span className={`${styles.chip} ${STATUS_CLASS[value] ?? ""}`}>
      <i aria-hidden="true" />
      {value}
    </span>
  );
}

